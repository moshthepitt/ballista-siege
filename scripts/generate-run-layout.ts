import { writeFile } from 'node:fs/promises';
import { address } from '@solana/kit';
import { createDeployment } from '../src/chain-v1/client.js';
import { TEMPLATE_NAMES } from '../src/chain-v1/templates.js';

export async function currentRunLayout() {
  const d = await createDeployment(address('11111111111111111111111111111111'));
  const c = d.compiled.state;
  if (c.accountGroupOrder.length || c.rowInputOrder.length || c.inputOrder.some(n => c.template.inputs[n].type !== 'u64')) throw new Error('State wire layout changed');
  return {
    inputs: c.inputOrder,
    accounts: c.fixedAccountOrder.map(name => ({ name, role: Number(!!c.template.accounts[name].writable) + 2 * Number(!!c.template.accounts[name].signer) })),
    registries: c.fixedAccountOrder.flatMap(name => {
      const registry = c.template.accounts[name].registry;
      return registry ? [{ name, index: c.registryOrder.indexOf(registry.name) }] : [];
    }),
  };
}
export async function generateRunLayout() {
  const layout = await currentRunLayout();
  await writeFile(new URL('../src/chain-v1/run-layout.ts', import.meta.url), `// Generated by scripts/generate-run-layout.ts. No template payloads.\nexport const TEMPLATE_NAMES = ${JSON.stringify(TEMPLATE_NAMES)} as const;\nexport type TemplateName = typeof TEMPLATE_NAMES[number];\nexport const RUN_LAYOUT = ${JSON.stringify(layout, null, 2)} as const;\n`);
}
if (process.argv[1]?.endsWith('generate-run-layout.ts')) await generateRunLayout();
